def lookup_macros(name: str) -> Optional[Tuple[float, float, float]]:
    """按名称查宏量营养素；未收录时按热量比例估算。"""
    name = (name or "").strip().lower()
    if not name:
        return None
    if name in FOOD_MACROS:
        return FOOD_MACROS[name]
    for key in sorted(FOOD_MACROS, key=len, reverse=True):
        if len(key) < 2:
            continue
        if key in name:
            return FOOD_MACROS[key]
    # 兜底：按 kcal 估算（蛋白 15%、碳水 55%、脂肪 30%）
    kcal100 = lookup(name) or 120
    protein = kcal100 * 0.15 / 4
    carbs = kcal100 * 0.55 / 4
    fat = kcal100 * 0.30 / 9
    return (round(protein, 1), round(carbs, 1), round(fat, 1))


def compute_macros(analysis: dict) -> Tuple[Dict[str, float], List[dict]]:
    """核算一份菜品的蛋白质/碳水/脂肪（克）。返回 (合计, 明细)。"""
    totals = {"protein": 0.0, "carbs": 0.0, "fat": 0.0}
    details: List[dict] = []
    for item in analysis.get("ingredients", []):
        if isinstance(item, dict):
            name = str(item.get("name", ""))
            weight = float(item.get("weight_g", 0) or 0)
        else:
            name = str(item)
            weight = 0.0
        p, c, f = lookup_macros(name) or (0.0, 0.0, 0.0)
        ratio = weight / 100.0
        gp, gc, gf = round(p * ratio, 1), round(c * ratio, 1), round(f * ratio, 1)
        totals["protein"] += gp
        totals["carbs"] += gc
        totals["fat"] += gf
        details.append({"name": name, "weight_g": weight, "protein": gp, "carbs": gc, "fat": gf})
    totals = {k: round(v, 1) for k, v in totals.items()}
    return totals, details

def lookup(name: str) -> Optional[int]:
    """Look up the calorie content (kcal/100g) for a food item by name.

    匹配顺序：精确匹配 → 食材名包含营养库条目（最长优先） → 简短通用名反向匹配。
    """
    name = (name or "").strip().lower()
    if not name:
        return None
    # 1) 精确匹配
    if name in FOOD_CALORIES:
        return FOOD_CALORIES[name]
    # 2) 食材名包含较长的营养库条目（如“花生米”匹配“花生”）
    for key in sorted(FOOD_CALORIES, key=len, reverse=True):
        if len(key) < 2:
            continue
        if key in name:
            return FOOD_CALORIES[key]
    # 3) 反向：短名匹配复合条目（仅当名称不是某条目的前缀时，避免 花生→花生油 类似误匹配）
    prefix_keys = [k for k in FOOD_CALORIES if len(k) > len(name) and k.startswith(name)]
    if not prefix_keys:
        for key in sorted(FOOD_CALORIES, key=len, reverse=True):
            if len(key) < 2:
                continue
            if name in key:
                return FOOD_CALORIES[key]
    return None


def compute_calories(analysis: dict) -> Tuple[int, List[dict], List[str]]:
    """
    Compute total calories from a dish analysis.

    Args:
        analysis: Dict with 'ingredients' and 'cooking_method' keys.

    Returns:
        Tuple of (total_calories, breakdown_list, unlisted_ingredients).
    """
    total = 0.0
    breakdown: List[dict] = []
    unlisted: List[str] = []

    for item in analysis.get("ingredients", []):
        if isinstance(item, dict):
            name = str(item.get("name", ""))
            weight = float(item.get("weight_g", 0) or 0)
        else:
            name = str(item)
            weight = 0.0

        kcal100 = lookup(name)
        if kcal100 is None:
            kcal100 = DEFAULT_PER_100G
            unlisted.append(name)

        cal = weight * kcal100 / 100.0
        breakdown.append({
            "name": name,
            "weight_g": weight,
            "kcal_per_100g": kcal100,
            "calories": round(cal),
        })
        total += cal

    # Add estimated oil for frying/stir-frying if not already listed
    method = (analysis.get("cooking_method") or "").lower()
    has_oil = any("\u6cb9" in b["name"] for b in breakdown)
    oil_add = 0
    if any(k in method for k in ("deep", "frit")):
        oil_add = FRY_OIL_G
    elif any(k in method for k in ("fry", "saut\u00e9", "stir", "pan")) and not has_oil:
        oil_add = STIR_OIL_G
    if oil_add:
        cal = oil_add * FOOD_CALORIES["\u98df\u7528\u6cb9"] / 100.0
        breakdown.append({
            "name": "\u98df\u7528\u6cb9\uff08\u4f30\u7b97\uff09", "weight_g": oil_add,
            "kcal_per_100g": FOOD_CALORIES["\u98df\u7528\u6cb9"], "calories": round(cal),
        })
        total += cal

    return round(total), breakdown, unlisted


def bmi(height_cm: float, weight_kg: float) -> float:
    """Calculate BMI from height (cm) and weight (kg)."""
    h = height_cm / 100.0
    return round(weight_kg / (h * h), 1)


def bmi_category(v: float) -> str:
    """Return Chinese BMI category string."""
    if v < 18.5:
        return "\u504f\u7626"
    if v < 24:
        return "\u6b63\u5e38"
    if v < 28:
        return "\u504f\u80d6"
    return "\u80a5\u80d6"


def tdee(height_cm: float, weight_kg: float, age: int, gender: str, activity: str) -> int:
    """Calculate Total Daily Energy Expenditure using Mifflin-St Jeor equation."""
    if gender == "\u7537":
        bmr = 10 * weight_kg + 6.25 * height_cm - 5 * age + 5
    else:
        bmr = 10 * weight_kg + 6.25 * height_cm - 5 * age - 161
    factors = {"\u4e45\u5750": 1.2, "\u8f7b\u5ea6": 1.375, "\u4e2d\u5ea6": 1.55, "\u9ad8\u5f3a\u5ea6": 1.725}
    return round(bmr * factors.get(activity, 1.2))

