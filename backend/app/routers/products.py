SEEDED = False


@router.get("", response_model=list[ProductOut])
def search_products(q: str = Query("", max_length=50), db: Session = Depends(get_db)):
    _ensure_seeded(db)
    if not q:
        return db.query(FoodProduct).limit(50).all()
    kw = f"%{q}%"
    return (
        db.query(FoodProduct)
        .filter(or_(FoodProduct.name.like(kw), FoodProduct.brand.like(kw)))
        .limit(30)
        .all()
    )


def _ensure_seeded(db: Session):
    global SEEDED
    if SEEDED:
        return
    if db.query(FoodProduct).count() == 0:
        for brand, name, serving, kcal, note in SEED:
            db.add(FoodProduct(brand=brand, name=name, serving=serving, kcal=kcal, note=note))
        db.commit()
        print(f"[products] 已写入 {len(SEED)} 条品牌商品热量数据")
    SEEDED = True
